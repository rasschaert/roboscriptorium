"""The primer's chart of the errors left: per cause, how many a question points at and
how many nothing asks about, a hundred pages, from the latest tuning and validation
benches that saved their errors.

    uv run python experiments/primer_errors.py > docs/primer/errors.svg

No models; rerun after a bench that moves the errors.
"""

import json
from collections import Counter
from html import escape
from pathlib import Path

BENCH = Path("work/bench")


def latest(set_name: str) -> Path:
    runs = sorted(BENCH.glob(f"{set_name}-*.errors.jsonl"))
    return runs[-1]


def main() -> None:
    rows, pages, runs = [], 0, []
    for set_name in ("tuning", "validation"):
        errors = latest(set_name)
        record = json.loads(errors.with_name(errors.name.replace(".errors.jsonl", ".json")).read_text())
        rows += [json.loads(line) for line in errors.read_text().splitlines() if line.strip()]
        pages += sum(len(b["pages"]) for b in record["books"].values())
        runs.append(f"{set_name} {record['at'][:10]}")
    asked = Counter(r["cause"] for r in rows if r["asked"])
    unasked = Counter(r["cause"] for r in rows if not r["asked"])
    causes = sorted(asked.keys() | unasked.keys(), key=lambda c: -(asked[c] + unasked[c]))
    per = 100 / pages
    scale = 60  # px for one place a hundred pages
    top, row, x0 = 74, 22, 210
    height = top + row * len(causes) + 82
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 760 {height}" '
        'font-family="Helvetica, Arial, sans-serif">',
        f'  <rect width="760" height="{height}" fill="#ffffff"/>',
        '  <text x="30" y="32" font-size="15" font-weight="bold" fill="#3b4252">'
        "The errors left, by cause: places a hundred pages</text>",
        '  <rect x="30" y="46" width="14" height="12" fill="#2e6db4"/>'
        '<text x="50" y="57" font-size="12" fill="#3b4252">a question points at it: your answer fixes it'
        "</text>",
        '  <rect x="340" y="46" width="14" height="12" fill="#c2671b"/>'
        '<text x="360" y="57" font-size="12" fill="#3b4252">nothing asks: it stays in the book</text>',
    ]
    for i, cause in enumerate(causes):
        y = top + i * row
        a, u = asked[cause] * per, unasked[cause] * per
        out.append(
            f'  <text x="{x0 - 10}" y="{y + 13}" font-size="12" fill="#3b4252" '
            f'text-anchor="end">{escape(cause)}</text>'
        )
        out.append(f'  <rect x="{x0}" y="{y + 2}" width="{a * scale:.1f}" height="14" fill="#2e6db4"/>')
        out.append(
            f'  <rect x="{x0 + a * scale:.1f}" y="{y + 2}" width="{u * scale:.1f}" height="14" '
            'fill="#c2671b"/>'
        )
        out.append(
            f'  <text x="{x0 + (a + u) * scale + 6:.1f}" y="{y + 13}" font-size="11" '
            f'fill="#4c566a">{a:.1f} + {u:.1f}</text>'
        )
    total_a, total_u = sum(asked.values()) * per, sum(unasked.values()) * per
    y = top + row * len(causes) + 22
    out.append(
        f'  <text x="30" y="{y}" font-size="12" fill="#3b4252">In all: {total_a:.0f} places asked and '
        f"<tspan font-weight=\"bold\">{total_u:.0f} unasked</tspan> a hundred pages, over "
        f"{pages:,} pages ({', '.join(runs)}).</text>"
    )
    out.append(
        f'  <text x="30" y="{y + 20}" font-size="11" fill="#7b8aa6">Before review; the causes '
        "are read from each error’s two sides (errorlog.cause); a place may be several words.</text>"
    )
    out.append(
        f'  <text x="30" y="{y + 36}" font-size="11" fill="#7b8aa6">Generated by '
        "experiments/primer_errors.py from the latest benches.</text>"
    )
    out.append("</svg>")
    print("\n".join(out))


if __name__ == "__main__":
    main()
